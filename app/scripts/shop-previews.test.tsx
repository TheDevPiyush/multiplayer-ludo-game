/**
 * Draws every shop item once, to the small images the shop shows (assets/shop/*.webp), and
 * writes components/cosmetics/previews.ts to list them. Drawing 40-odd boards and pawns live
 * as SVG made the shop stutter while scrolling; images scroll freely.
 *
 * Run after changing any item's art:  npm run shop-previews
 * (a bun test only so it can stand in plain SVG for react-native-svg).
 */
import { mock, test } from 'bun:test';
import { mkdirSync, writeFileSync } from 'fs';
import { join } from 'path';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import sharp from 'sharp';

const tag = (name: string) => (props: Record<string, unknown>) => React.createElement(name, props);
const Svg = (props: Record<string, unknown>) => React.createElement('svg', { xmlns: 'http://www.w3.org/2000/svg', ...props });
mock.module('react-native-svg', () => ({
    __esModule: true, default: Svg, Svg,
    Circle: tag('circle'), Ellipse: tag('ellipse'), G: tag('g'), Line: tag('line'), Path: tag('path'),
    Polygon: tag('polygon'), Rect: tag('rect'), Stop: tag('stop'), Defs: tag('defs'),
    LinearGradient: tag('linearGradient'), RadialGradient: tag('radialGradient'), ClipPath: tag('clipPath'),
}));
// The board's geometry reads the window width; previews are drawn at a fixed size anyway.
mock.module('react-native', () => ({
    Dimensions: { get: () => ({ width: 476, height: 900 }) },
    View: (p: { children?: React.ReactNode }) => React.createElement(React.Fragment, null, p.children),
    StyleSheet: { create: (s: unknown) => s, absoluteFill: {} },
    Platform: { OS: 'web' },
    Pressable: tag('g'),
}));

/** Pixel sizes, about 2.5× what a shop card shows. */
export const SIZES = { board: 480, pawn: { w: 320, h: 200 }, dice: 260 } as const;

test('shop previews', async () => {
    const { itemIds } = await import('../components/cosmetics/items');
    const { LudoBoard } = await import('../components/ludo/LudoBoard');
    const { Pawn } = await import('../components/cosmetics/PawnArt');
    const { Dice3D } = await import('../components/ludo/DiceArt');
    const { COLOR_HEX } = await import('../components/ludo/geometry');

    const root = join(import.meta.dir, '..');
    mkdirSync(join(root, 'assets/shop'), { recursive: true });
    const ids = itemIds();

    for (const id of ids) {
        let svg: string;
        if (id.startsWith('board.')) {
            svg = renderToStaticMarkup(<LudoBoard theme={id} size={SIZES.board} />);
        } else if (id.startsWith('pawn.')) {
            const pw = 150;
            svg = renderToStaticMarkup(
                <svg xmlns="http://www.w3.org/2000/svg" width={SIZES.pawn.w} height={SIZES.pawn.h}>
                    <g transform={`translate(4 ${SIZES.pawn.h - pw * 1.3})`}><Pawn color="RED" width={pw} skin={id} /></g>
                    <g transform={`translate(${SIZES.pawn.w - pw - 4} ${SIZES.pawn.h - pw * 1.3})`}><Pawn color="BLUE" width={pw} skin={id} /></g>
                </svg>,
            );
        } else {
            svg = renderToStaticMarkup(<Dice3D value={5} size={SIZES.dice} color={COLOR_HEX.RED!} skin={id} />);
        }
        await sharp(Buffer.from(svg)).webp({ quality: 84, alphaQuality: 90, effort: 6 }).toFile(join(root, `assets/shop/${id}.webp`));
    }

    const lines = ids.map(id => `    '${id}': require('@/assets/shop/${id}.webp'),`);
    writeFileSync(
        join(root, 'components/cosmetics/previews.ts'),
        `// Generated by scripts/shop-previews.test.tsx (npm run shop-previews). Do not edit.
import type { ImageSourcePropType } from 'react-native';

/** A pre-drawn image of each shop item, for the shop's cards. */
export const PREVIEWS: Record<string, ImageSourcePropType> = {
${lines.join('\n')}
};

/** Width ÷ height of each kind's preview image. */
export const PREVIEW_ASPECT = { board: 1, pawn: ${SIZES.pawn.w / SIZES.pawn.h}, dice: ${(1 / 1.08).toFixed(4)} } as const;
`,
    );
}, 120_000);
